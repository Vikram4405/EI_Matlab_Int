% build_mex.m - Compiles Edge Impulse Coffee Machine Vibration Classifier into MATLAB MEX
fprintf('=== Building Edge Impulse MEX Classifier ===\n');

baseDir = pwd;
eiDir = fullfile(baseDir, 'edge_impulse_model');

% Include directories
includeDirs = { ...
    ['-I' fullfile(baseDir)], ...
    ['-I' fullfile(eiDir)], ...
    ['-I' fullfile(eiDir, 'model-parameters')], ...
    ['-I' fullfile(eiDir, 'tflite-model')], ...
    ['-I' fullfile(eiDir, 'edge-impulse-sdk')], ...
    ['-I' fullfile(eiDir, 'edge-impulse-sdk', 'classifier')], ...
    ['-I' fullfile(eiDir, 'edge-impulse-sdk', 'porting')] ...
};

% Compile definitions
defs = { ...
    'COMPFLAGS="$COMPFLAGS /std:c++20 /EHsc /w"', ...
    '-DEI_PORTING_POSIX=0', ...
    '-DEI_PORTING_MINGW32=0', ...
    '-DEIDSP_USE_CMSIS_DSP=0', ...
    '-DEIDSP_LOAD_CMSIS_DSP_SOURCES=0' ...
};

% Targeted source files
sources = { ...
    fullfile(baseDir, 'ei_classifier_mex.cpp'), ...
    fullfile(eiDir, 'tflite-model', 'tflite_learn_1061472_40_compiled.cpp'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'dsp', 'memory.cpp'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'dsp', 'kissfft', 'kiss_fft.cpp'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'dsp', 'kissfft', 'kiss_fftr.cpp'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'core', 'api', 'common.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'core', 'api', 'error_reporter.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'kernels', 'kernel_util_lite.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'kernels', 'internal', 'quantization_util.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'kernels', 'internal', 'portable_tensor_utils.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'kernels', 'kernel_util_micro.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'kernels', 'fully_connected.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'kernels', 'fully_connected_common.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'kernels', 'softmax.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'kernels', 'softmax_common.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'micro_log.cc'), ...
    fullfile(eiDir, 'edge-impulse-sdk', 'tensorflow', 'lite', 'micro', 'micro_string.cc') ...
};

fprintf('Compiling %d targeted source files into ei_classifier_mex.mexw64...\n', length(sources));
try
    mex(includeDirs{:}, defs{:}, sources{:}, '-output', 'ei_classifier_mex');
    fprintf('\n********************************************************\n');
    fprintf(' SUCCESS: ei_classifier_mex.mexw64 built successfully!\n');
    fprintf('********************************************************\n');
catch ME
    fprintf('COMPILATION FAILED:\n%s\n', ME.message);
end
